export interface ChapterParagraph {
  text: string
  heading: boolean
}

export interface ParsedChapter {
  title: string
  paragraphs: ChapterParagraph[]
}

export interface ParsedBook {
  title: string
  author: string
  coverDataUrl: string | null
  chapters: ParsedChapter[]
}

interface BasePost {
  chapterIndex: number
  /** Normalized, display-ready chapter title (e.g. bare "1" becomes "Chapter 1"). */
  chapterTitle: string
  /** Estimated minutes left in this post's chapter, from this post onward. */
  minutesLeft: number
}

export type Post =
  | ({ type: 'text'; text: string } & BasePost)
  | ({ type: 'heading'; text: string } & BasePost)

export interface LibraryEntry {
  id: string
  title: string
  author: string
  coverDataUrl: string | null
  addedAt: number
  totalPosts: number
  currentIndex: number
  /** Word-weighted reading progress, 0-100. More accurate than a post-index ratio. */
  progressPct: number
}

export interface StoredBook {
  meta: LibraryEntry
  posts: Post[]
  /** Indices (into `posts`) the reader has starred. */
  highlights?: number[]
  /** Chapter indices the reader has saved, shown in the separate Bookmarks tab. */
  bookmarks?: number[]
  /** Chapter indices the reader has "loved" — a personal marker, not a public count. */
  loves?: number[]
  /** Cached AI-written recaps, keyed by chapterIndex. Generated by the summarize API but not currently surfaced in the feed UI. */
  chapterSummaries?: Record<number, string>
}

/** A reader comment that quotes a specific passage from the book. */
export interface PassageQuote {
  text: string
  permalink: string
  subreddit: string
  author: string
}

/** A discussion thread covering a run of chapters (e.g. r/bookclub's
 * "Chapters 1-5"). Surfaced in that chapter's comment section once the
 * reader has finished it. */
export interface ChapterThreadInfo {
  title: string
  permalink: string
  subreddit: string
  /** 1-based: the last chapter number this thread's discussion covers. */
  throughChapter: number
}

/** Everything to show in one chapter's end-of-chapter comment section. */
export interface ChapterDiscussion {
  comments: PassageQuote[]
  thread?: ChapterThreadInfo
}

export interface BookReview {
  text: string
  rating: number | null
  permalink: string | null
}

export interface DiscussionsResponse {
  quotes: PassageQuote[]
  chapterThreads: ChapterThreadInfo[]
  reviews: BookReview[]
  /** True when no Reddit/Hardcover credentials are configured server-side
   * and this is synthesized demo data, not real reader discussion. */
  mock: boolean
}
